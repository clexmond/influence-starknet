"""Generate a BN254 scalar-field Poseidon2 permutation using Cairo modular builtins.
Constants and matrix match the pinned original model; no offchain execution hints.
"""
import json
from pathlib import Path
from garaga.modulo_circuit import ModuloCircuit
from garaga.modulo_circuit_structs import u384
from garaga.curves import CurveID

params=json.loads(Path(__file__).with_name('poseidon2-constants.json').read_text())
c=ModuloCircuit('GRUMPKIN_POSEIDON2',CurveID.GRUMPKIN.value,compilation_mode=1)
state=[c.write_struct(u384(name=f's{i}',elmts=[c.field(i)])) for i in range(4)]
def const(v): return c.set_or_get_constant(int(v))
def add(*args):
    acc=args[0]
    for value in args[1:]: acc=c.add(acc,value)
    return acc
def external(s):
    matrix=[[5,7,1,3],[4,6,1,1],[1,3,5,7],[1,1,4,6]]
    return [add(*[c.mul(x,const(k)) if k!=1 else x for x,k in zip(s,row)]) for row in matrix]
def fifth(x):
    square=c.mul(x,x)
    return c.mul(c.mul(square,square),x)
state=external(state)
for r in range(64):
    if r<4 or r>=60:
        state=external([fifth(c.add(x,const(params['round_constants'][r][j]))) for j,x in enumerate(state)])
    else:
        state[0]=fifth(c.add(state[0],const(params['round_constants'][r][0])))
        total=add(*state)
        state=[c.add(c.mul(x,const(params['mat_internal_diag_m_1'][j])),total) for j,x in enumerate(state)]
for i,x in enumerate(state): c.extend_struct_output(u384(name=f'o{i}',elmts=[x]))
code,name=c.compile_circuit(function_name='GRUMPKIN_POSEIDON2',pub=True,inline=False,generic_modulus=True)
header='''// Generated by generate-poseidon2.py using pinned Garaga 1.1.0.
use core::circuit::{CircuitElement as CE, CircuitInput as CI, CircuitInputs, CircuitOutputsTrait, EvalCircuitTrait, circuit_add, circuit_mul, u384};
use garaga::core::circuit::{AddInputResultTrait2, u288IntoCircuitInputValue};
'''
Path(__file__).with_name('src').joinpath('poseidon2.cairo').write_text(header+code)
print(name)
